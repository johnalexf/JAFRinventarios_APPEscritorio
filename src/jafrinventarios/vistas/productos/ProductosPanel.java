    // Disponible para cuando se muestren los productos a un usuario no administrador
    public void ocultarTituloEditar(){
        contenedorTitulosTabla.remove(lblTituloEditar);
        contenedorTitulosTabla.revalidate(); // Re calcula el diseño GridBagLayout
        contenedorTitulosTabla.repaint();    // Redibuja el panel en pantalla
    }
    
    public PanelBusquedaYAccionLibre getPanelBusquedaYAccionLibre(){
        return panelBusquedaYAccionLibre;
    }
    
    /*
    Metodo para poder agregar toda la lista deproductos recibida, por medio de
    LinkedHashMap mantenemos el orden en el cual ha sido enviada.
    */
    public void inyectarFilas( LinkedHashMap<Integer, FilaTablaProductos> filasTablaProductos ){
        removerContenido();
        
        filasTablaProductos.values().forEach(fila -> {
            contenedorContenidoTabla.add(fila);
        });
        
        redubijarPanel();
    }
    
    public void removerContenido(){
        //Remover todo el contenido dentro del contenedorContenidoTabla
        contenedorContenidoTabla.removeAll();
    }
    
    /*
    Metodo para inyectar una nueva fila, pensado unicamente para cuando se cree
    un nuevo producto
    */
    public void inyectarNuevaFila( FilaTablaProductos fila ){
        contenedorContenidoTabla.add(fila);
        redubijarPanel();
    }
    
    public void eliminarFila ( FilaTablaProductos fila ){
        contenedorContenidoTabla.remove( fila );
        redubijarPanel();
    }
    
    
    private void redubijarPanel(){
        // Avisar a Swing que recalcule los tamaños y redibuje el panel
        contenedorContenidoTabla.revalidate();
        contenedorContenidoTabla.repaint();
    }
  
    
    

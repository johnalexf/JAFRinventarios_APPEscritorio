    /*
    Estos setter son privados puesto que el controlador tendra que mandar toda
    la informacion ya sea para actualizar la fila o asignar los datos iniciales.
    */
    private void setId(String dato) {
        this.lblDatoId.setText(dato);
    }

    private void setNombre(String dato) {
        this.lblDatoNombre.setText(dato);
    }
    
    private void setProveedor (String dato) {
        this.lblDatoProveedor.setText(dato);
    }

    private void setPrecioCompra ( double precio ) {
        this.lblDatoPrecioCompra.setText( precioAString(precio) );
    }

    private void setPrecioVenta( double precio ) {
        this.lblDatoPrecioVenta.setText( precioAString(precio) );
    }

    private void setCantidadDisponible( int cantidad ) {
        this.lblDatoCantidadDisponible.setText( Integer.toString(cantidad) );
    }
    
    private void setCantidadMinStock( int cantidad ) {
        this.lblDatoCantidadMinStock.setText( Integer.toString(cantidad) );
    }
    
    
    /*
    Metodo para estandarizar la conversion de un precio con su simbolo
    */
    private String precioAString ( double precio ){
        return String.format("$%.2f", precio);
    }

    

    //SETTERS
    
    public void setDatos(   int id,
                            String nombreProveedor,
                            String fecha,
                            double totalVenta,
                            String aliasUsuario ){
    
        setId(id);
        setProveedor(nombreProveedor);
        setFecha(fecha);
        setTotal(totalVenta);
        setAliasUsuario(aliasUsuario);
        
    }

    
    // Disponible para cuando se muestren las compras a un usuario no administrador
    public void ocultarBtnEditar(){
        contenedorDatosGenerales.remove(btnEditar);
        contenedorDatosGenerales.revalidate(); // Re calcula el diseño GridBagLayout
        contenedorDatosGenerales.repaint();    // Redibuja el panel en pantalla
    }
    
    
    public void inyectarFilasDetalles( ArrayList<FilaTablaDetalleCompra> filasDetallesCompra ){
        contenedorDetallesCompra.removeAll();
        
        filasDetallesCompra.forEach(fila -> {
            contenedorDetallesCompra.add(fila);
        });
        
        redibujarPanel();
    }
    
    private void redibujarPanel(){
        contenedorGlobalDetallesCompra.revalidate();
        contenedorGlobalDetallesCompra.repaint();
    }
    
    

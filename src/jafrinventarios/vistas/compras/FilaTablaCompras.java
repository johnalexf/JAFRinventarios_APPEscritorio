    /*
    Estos setter son privados puesto que el controlador tendra que mandar toda
    la informacion ya sea para actualizar la fila o asignar los datos iniciales.
    */
    private void setId( int  id ) {
        this.lblDatoId.setText( Integer.toString(id) );
    }
    
    private void setProveedor (String dato) {
        this.lblDatoProveedor.setText(dato);
    }

    private void setFecha ( String fecha ) {
        this.lblDatoFecha.setText( fecha );
    }

    private void setTotal( double precio ) {
        this.lblDatoTotal.setText( precioAString(precio) );
    }

    private void setAliasUsuario( String aliasUsuario ) {
        this.lblDatoAliasUsuario.setText( aliasUsuario );
    }
    
    
    /*
    Metodo para estandarizar la conversion de un precio con su simbolo
    */
    private String precioAString ( double precio ){
        return String.format("$%.2f", precio);
    }

    
